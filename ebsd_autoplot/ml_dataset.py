"""Native numeric patch access and specimen-grouped ML split policy.

Torch is strictly optional and imported only by make_torch_dataset. The normal
reader returns numpy arrays. Variable patch shapes require a caller collator,
or export with pad-with-mask. No labels are generated by this module.
"""
from __future__ import annotations
import json
from pathlib import Path
import h5py
import numpy as np


class PatchDataset:
    def __init__(self, index_file, channels=None, entries=None):
        self.index_files = [Path(p) for p in index_file] if isinstance(index_file, (tuple, list)) else [Path(index_file)]
        self.entries = []
        for file in self.index_files:
            data = json.loads(file.read_text(encoding="utf-8"))
            if data.get("schema_version") != 1:
                raise ValueError("Unsupported patch database schema")
            for entry in data["entries"]:
                path = (file.parent / entry["file"]).resolve()
                if file.parent.resolve() not in path.parents:
                    raise ValueError("Patch index path escapes its database")
                self.entries.append(dict(entry, resolved_file=str(path)))
        if entries is not None:
            self.entries = [self.entries[int(i)] for i in entries]
        self.channels = tuple(channels) if channels is not None else None

    def __len__(self):
        return len(self.entries)

    def __getitem__(self, index):
        entry = self.entries[index]
        with h5py.File(entry["resolved_file"], "r") as src:
            selected = self.channels or tuple(src["channels"])
            missing = set(selected) - set(src["channels"])
            if missing:
                raise ValueError(f"Requested unavailable patch channels: {sorted(missing)}")
            return {"channels": {key: src["channels"][key][:] for key in selected},
                    "masks": {key: src["masks"][key][:].astype(bool) for key in selected},
                    "padding_mask": src["padding_mask"][:].astype(bool),
                    "metadata": json.loads(src.attrs["metadata_json"])}


def grouped_split(entries, fractions=(.7, .15, .15), seed=0, group_key="split_group"):
    """Return train/validation/test row indexes with disjoint specimens/scans.

    The split unit is a specimen, or original scan when no specimen identity is
    available. Patch IDs cannot be used as group_key. Too few independent groups
    is an explicit error. No claim is made of stratification by unavailable labels.
    """
    if group_key not in ("split_group", "parent_id", "source_id", "specimen_id"):
        raise ValueError("Split must group an independent specimen or original scan")
    fractions = np.asarray(fractions, float)
    if fractions.shape != (3,) or not np.isfinite(fractions).all() or np.any(fractions < 0) or not np.isclose(fractions.sum(), 1):
        raise ValueError("Split fractions must be finite nonnegative train/validation/test fractions summing to 1")
    if any(group_key not in row or not str(row[group_key]).strip() for row in entries):
        raise ValueError("Every patch needs an explicit original-source split group")
    groups = sorted({str(row[group_key]) for row in entries})
    active = int(np.count_nonzero(fractions))
    if len(groups) < active:
        raise ValueError("Too few independent specimen/scan groups for the requested split")
    rng = np.random.default_rng(seed); groups = np.asarray(groups)[rng.permutation(len(groups))]
    # Guarantee each requested subset at least one group, distribute remainder.
    counts = (fractions > 0).astype(int)
    remain = len(groups) - int(counts.sum())
    weights = fractions * remain
    counts += np.floor(weights).astype(int)
    for i in np.argsort(-(weights - np.floor(weights)))[:len(groups) - int(counts.sum())]:
        counts[i] += 1
    result = {}; start = 0
    for name, count in zip(("train", "validation", "test"), counts):
        selected = set(groups[start:start + count].tolist()); start += count
        result[name] = [i for i, row in enumerate(entries) if str(row[group_key]) in selected]
    # A specimen key may be wrong; catch original scans straddling subsets too.
    original_groups = []
    for indexes in result.values():
        original_groups.append({str(entries[i].get("parent_id", entries[i].get("source_id"))) for i in indexes})
    if any(original_groups[i] & original_groups[j] for i in range(3) for j in range(i)):
        raise ValueError("Original scan would appear in multiple subsets; repair specimen metadata")
    return result


class TorchPatchDataset(PatchDataset):
    """Spawn-picklable map dataset; Torch is imported only when read."""
    def __getitem__(self,index):
        import torch
        sample=super().__getitem__(index)
        sample['channels']={k:torch.from_numpy(v) for k,v in sample['channels'].items()}
        sample['masks']={k:torch.from_numpy(v) for k,v in sample['masks'].items()}
        sample['padding_mask']=torch.from_numpy(sample['padding_mask'])
        return sample


def collate_patch_batch(samples):
    """Keep metadata intact; variable shapes remain explicit lists, never resize."""
    import torch
    if not samples:raise ValueError('Empty patch batch')
    shape=samples[0]['padding_mask'].shape
    if any(s['padding_mask'].shape!=shape for s in samples):
        return {'variable_shape':True,'samples':samples,'metadata':[s['metadata'] for s in samples]}
    keys=set(samples[0]['channels'])
    if any(set(s['channels'])!=keys for s in samples):
        raise ValueError('Choose common channels explicitly before batching modalities')
    return {'variable_shape':False,'channels':{k:torch.stack([s['channels'][k] for s in samples]) for k in keys},
        'masks':{k:torch.stack([s['masks'][k] for s in samples]) for k in keys},
        'padding_mask':torch.stack([s['padding_mask'] for s in samples]),'metadata':[s['metadata'] for s in samples]}


def make_torch_dataset(index_file, channels=None, entries=None):
    """Return torch.utils.data.Dataset with tensors and explicit per-channel masks."""
    try:
        import torch
        from torch.utils.data import Dataset
    except ImportError as error:
        raise RuntimeError("Torch is optional; install ML dependencies to request tensor datasets") from error
    return TorchPatchDataset(index_file,channels,entries)


def make_torch_dataloader(index_file,channels=None,entries=None,*,batch_size=1,num_workers=0):
    from torch.utils.data import DataLoader
    return DataLoader(make_torch_dataset(index_file,channels,entries),batch_size=batch_size,
                      num_workers=num_workers,collate_fn=collate_patch_batch)


def load_graph_tensor(graph_file, *, pyg=False):
    """Load real adjacency tensors; optional PyG Data, no learned GNN claims."""
    try:
        import torch
    except ImportError as error:
        raise RuntimeError("Torch is optional; install ML dependencies for graph tensors") from error
    with np.load(graph_file, allow_pickle=False) as archive:
        data = {"x": torch.from_numpy(archive["node_features"].astype(np.float32)),
                "x_mask": torch.from_numpy(archive["node_feature_mask"]),
                "edge_index": torch.from_numpy(archive["edge_index"]),
                "edge_attr": torch.from_numpy(archive["edge_attr"].astype(np.float32)),
                "edge_mask": torch.from_numpy(archive["edge_feature_mask"]),
                "grain_id": torch.from_numpy(archive["node_ids"]),
                "phase_id": torch.from_numpy(archive["node_phase_id"]),
                "orientation_xyzw": torch.from_numpy(archive["orientation_xyzw"]),
                "source_id": str(archive["source_id"]),
                "node_feature_names": archive["node_feature_names"].tolist(),
                "edge_feature_names": archive["edge_feature_names"].tolist()}
    if pyg:
        try:
            from torch_geometric.data import Data
        except ImportError as error:
            raise RuntimeError("PyTorch Geometric is optional; install it to request PyG Data") from error
        return Data(**data)
    return data
